export const getAllStates = () => Object.keys(INDIA_GEO_DATA);

export const getDistrictsForState = (state) => {
  if (!state || !INDIA_GEO_DATA[state]) return [];
  return Object.keys(INDIA_GEO_DATA[state]);
};

export const getCitiesForDistrict = (state, district) => {
  if (!state || !district || !INDIA_GEO_DATA[state] || !INDIA_GEO_DATA[state][district]) return [];
  return INDIA_GEO_DATA[state][district];
};

export const getTalukasForDistrict = (state, district) => {
  const cities = getCitiesForDistrict(state, district);
  const talukas = new Set();
  cities.forEach(c => {
    if (c.taluka) talukas.add(c.taluka);
  });
  if (talukas.size === 0) {
    // If no explicit taluka field, use city names as sub-areas
    return cities.map(c => c.city);
  }
  return Array.from(talukas);
};

